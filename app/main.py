async def _match_uploaded_resume(file: UploadFile):
    """Upload -> validated text -> Agent 1. Returns (agent1_result, None) or (None, error JSONResponse)."""
    # Read at most limit+1 bytes so an oversized upload can't exhaust memory.
    data = await file.read(security.MAX_UPLOAD_BYTES + 1)
    try:
        safe_name = security.validate_upload(file.filename, data)
    except security.ValidationError as exc:
        return None, JSONResponse(status_code=400, content={"status": "invalid_upload", "message": str(exc)})

    # Random temp name (never the user-supplied one); only the vetted
    # extension is kept so the parser can dispatch on it.
    suffix = Path(safe_name).suffix.lower()
    with tempfile.NamedTemporaryFile(delete=False, suffix=suffix) as tmp:
        tmp.write(data)
        tmp_path = tmp.name

    try:
        try:
            resume_text = extract_resume_text(tmp_path)
        except (FileNotFoundError, ValueError):
            return None, JSONResponse(
                status_code=400,
                content={
                    "status": "extraction_failed",
                    "message": "No readable text could be extracted from this file. Upload a text-based PDF, DOCX or TXT resume.",
                },
            )
        except Exception as exc:  # malformed/hostile PDF or DOCX: parser libraries raise many types
            log.warning("Resume parsing failed: %s", security.redact(exc))
            return None, JSONResponse(
                status_code=400,
                content={"status": "extraction_failed", "message": "The file could not be parsed as a valid resume."},
            )

        # Character-set + length restriction on the only free-form text that
        # reaches embeddings / prompts (guideline G).
        resume_text = security.sanitize_prompt_text(resume_text, security.MAX_RESUME_CHARS)
        if not resume_text:
            return None, JSONResponse(
                status_code=400,
                content={"status": "extraction_failed", "message": "The resume contained no usable text."},
            )
        flags = security.detect_injection(resume_text)
        if flags:
            security.audit("prompt_injection_suspected", actor="A1", outcome="flagged", stream="llm",
                           resource="resume_upload", details={"indicators": flags})
        return run_agent1(resume_text), None
    finally:
        try:
            os.unlink(tmp_path)
        except OSError:
            pass


def _unmatched_response(agent1_result):
    """The non-auto_matched outcomes, shared by /api/generate and /api/match (None when auto_matched)."""
    status = agent1_result["status"]
    if status == "no_match_found":
        return {"status": status, "message": "No role matched this resume closely enough to proceed."}
    if status == "blueprint_unavailable":
        top = agent1_result["match_info"]["top_match"]
        return {
            "status": status,
            "message": (
                f"Matched role_id '{top['role_id']}' but no blueprint could be built "
                "(likely a reference-only role with no role_master entry)."
            ),
        }
    if status == "needs_human_confirmation":
        candidates = [
            _blueprint_summary(bp)
            for bp in agent1_result["candidate_blueprints"]
            if bp["success"]
        ]
        return _label_ai({
            "status": status,
            "gap": agent1_result["match_info"]["gap"],
            "candidates": candidates,
            "message": "Two roles matched closely -- human confirmation needed before generating questions.",
        })
    return None


@app.post("/api/match", dependencies=[Depends(require_api_token)])
async def match(file: Annotated[UploadFile, File(...)]):
    """Resume -> matched role only (Agent 1, embeddings, no LLM). The SME then
    decides how many questions and at what level (see /api/generate-for-role)."""
    agent1_result, error = await _match_uploaded_resume(file)
    if error:
        return error
    unmatched = _unmatched_response(agent1_result)
    if unmatched:
        return unmatched
    return _label_ai({"status": "auto_matched", "match": _blueprint_summary(agent1_result["blueprint"])})


@app.post("/api/generate", dependencies=[Depends(require_api_token)])
async def generate(
    file: Annotated[UploadFile, File(...)],
    max_items: Annotated[int, Form(ge=1, le=10)] = 5,
):
    agent1_result, error = await _match_uploaded_resume(file)
    if error:
        return error
    unmatched = _unmatched_response(agent1_result)
    if unmatched:
        return unmatched

    # auto_matched
    blueprint = agent1_result["blueprint"]
    summary = _blueprint_summary(blueprint)

    try:
        question_result = generate_questions_for_blueprint(blueprint, max_items=max_items)
    except (RuntimeError, ValueError) as exc:
        log.warning("Question generation failed: %s", security.redact(exc))
        return {
            "status": "questions_unavailable",
            "match": summary,
            "message": "Questions could not be generated right now. Please try again shortly.",
        }

    return _label_ai({
        "status": "auto_matched",
        "match": summary,
        "items": question_result["items"],
        "skills_skipped": question_result["skills_skipped"],
        "counts": question_result["counts"],
    })


class GenerateForRoleRequest(BaseModel):
    # The SME's assessment design: which role, how many questions, at what
    # proficiency level (None = each skill's own role target), optionally
    # only for some of the role's skills.
    role_id: str = Field(pattern=_ID_RE)
    max_items: int = Field(ge=1, le=10)
    level: int | None = Field(default=None, ge=1, le=5)
    skills: list[Annotated[str, Field(max_length=200)]] | None = Field(default=None, max_length=20)


@app.post("/api/generate-for-role", dependencies=[Depends(require_api_token)])
async def generate_for_role(payload: GenerateForRoleRequest):
    blueprint = build_blueprint(payload.role_id)
    if not blueprint["success"]:
        return JSONResponse(status_code=400, content={"message": "Unknown role."})
    if payload.level:
        blueprint = with_assessment_level(blueprint, payload.level)
    if payload.skills:
        wanted = set(payload.skills)
        blueprint = {**blueprint, "skills": [s for s in blueprint["skills"] if s["skill"] in wanted]}
    try:
        result = generate_questions_for_blueprint(blueprint, max_items=payload.max_items)
    except (RuntimeError, ValueError) as exc:
        return _ai_unavailable(exc, "generate-for-role")
    return _label_ai({
        "status": "generated", "match": _blueprint_summary(blueprint), "level": payload.level,
        "items": result["items"], "skills_skipped": result["skills_skipped"], "counts": result["counts"],
    })


# ---------------------------------------------------------------------------
# Request models: whitelist validation for every field a client can send.
# ---------------------------------------------------------------------------

MAX_ITEMS_PER_REQUEST = 50
_OPTION_RE = re.compile(r"^[A-Da-d]$")


def _validate_answers(answers: dict[str, str]) -> dict[str, str]:
    if len(answers) > MAX_ITEMS_PER_REQUEST:
        raise ValueError("Too many answers.")
    for key, value in answers.items():
        if len(key) > 100:
            raise ValueError("Answer key too long.")
        if len(value) > security.MAX_ANSWER_CHARS:
            raise ValueError("Answer too long.")
    return answers


class ScoreRequest(BaseModel):
    # items are the exact objects /api/generate returned -- the frontend
    # holds them in memory and posts them back alongside the candidate's
    # answers, since there's no server-side session store for this demo.
    items: list[dict[str, Any]] = Field(max_length=MAX_ITEMS_PER_REQUEST)
    answers: dict[str, str]

    @field_validator("answers")
    @classmethod
    def _check_answers(cls, answers):
        _validate_answers(answers)
        # /api/score takes multiple-choice selections only.
        for value in answers.values():
            if value and not _OPTION_RE.match(value):
                raise ValueError("MCQ answers must be A, B, C or D.")
        return answers


@app.post("/api/score", dependencies=[Depends(require_api_token)])
async def score(payload: ScoreRequest):
    try:
        return score_assessment(payload.items, payload.answers)
    except (KeyError, TypeError, ValueError):
        return JSONResponse(status_code=400, content={"message": "The submitted items or answers are malformed."})


