"""
main.py

Sub-step 20 (Phase 5), extended at sub-step 21: the first slice of the
HLD's L1 Presentation layer -- a single FastAPI process serving the API
routes for the full pipeline built in agents/:
uploaded resume file -> extract_resume_text -> run_agent1 (match +
blueprint) -> generate_questions_for_blueprint (Agent 2, question
generation + self-check) -> score_assessment (Agent 3, scoring the
candidate's selected answers).

Single process, no separate frontend build step, no infra provisioning --
matches the HLD's stated constraints. Returns plain JSON.

Security controls (Hackfest secure-coding guidelines):
  - every /api route requires a bearer token (TALENT360_BACKEND_TOKEN),
    compared in constant time; fails closed outside debug mode
  - upload allowlist + size cap + magic-byte check, random temp file name
  - strict request-model validation (types, ranges, id patterns, sizes)
  - per-client rate limiting (DoS / cost control for LLM-backed routes)
  - errors never echo exception text, provider URLs or stack traces
  - security headers + no-store caching on API responses
  - audit trail for every API call (logs/audit.jsonl)
  - AI-generated output is labelled and flagged for human review
"""

