_ID_RE = r"^[A-Za-z0-9_\-]{1,100}$"

_RATE_LIMITS = {  # path prefix -> (max requests, window seconds) per client
    "/api/generate": (10, 60),
    "/api/case-studies": (20, 60),
    "/api/evidence": (20, 60),
    "/api/simulation": (60, 60),
    "/api/match": (20, 60),
    "/api/devplan": (20, 60),
    "/api/training-outline": (20, 60),
    "/api/score": (60, 60),
}
_DEFAULT_LIMIT = (60, 60)
_hits: dict[str, deque] = defaultdict(deque)
_hits_lock = threading.Lock()


def _client_id(request: Request) -> str:
    return request.client.host if request.client else "unknown"


def _rate_limited(request: Request) -> bool:
    path = request.url.path
    limit, window = next((v for k, v in _RATE_LIMITS.items() if path.startswith(k)), _DEFAULT_LIMIT)
    key = f"{_client_id(request)}:{path.split('/')[2] if path.count('/') > 1 else path}"
    now = time.monotonic()
    with _hits_lock:
        bucket = _hits[key]
        while bucket and now - bucket[0] > window:
            bucket.popleft()
        if len(bucket) >= limit:
            return True
        bucket.append(now)
    return False


def require_api_token(request: Request) -> None:
    """Bearer-token gate for every /api route (broken-access-control control)."""
    if not API_TOKEN:  # debug mode only -- startup refuses this otherwise
        return
    header = request.headers.get("authorization", "")
    scheme, _, supplied = header.partition(" ")
    if scheme.lower() != "bearer" or not security.token_matches(supplied.strip(), API_TOKEN):
        security.audit(
            "auth_failed", actor=_client_id(request), outcome="denied",
            resource=request.url.path, details={"reason": "missing or invalid bearer token"},
        )
        raise HTTPException(status_code=401, detail="Authentication required")


@app.middleware("http")
async def api_guard(request: Request, call_next):
    path = request.url.path
    started = time.monotonic()

    if path.startswith("/api/") and _rate_limited(request):
        security.audit("rate_limited", actor=_client_id(request), outcome="http_429", resource=path)
        return JSONResponse(status_code=429, content={"message": "Too many requests. Please slow down."},
                            headers={"Retry-After": "60"})

    response = await call_next(request)

    response.headers["X-Content-Type-Options"] = "nosniff"
    response.headers["X-Frame-Options"] = "DENY"
    response.headers["Referrer-Policy"] = "no-referrer"
    response.headers["Content-Security-Policy"] = "default-src 'none'; frame-ancestors 'none'"
    if not DEBUG_MODE:
        response.headers["Strict-Transport-Security"] = "max-age=31536000; includeSubDomains"
    if path.startswith("/api/"):
        response.headers["Cache-Control"] = "no-store"
        security.audit(
            "api_call", actor=_client_id(request), resource=f"{request.method} {path}",
            outcome="success" if response.status_code < 400 else f"http_{response.status_code}",
            details={"ms": int((time.monotonic() - started) * 1000)},
        )
    return response


@app.exception_handler(HTTPException)
async def http_exception_handler(request: Request, exc: HTTPException):
    return JSONResponse(status_code=exc.status_code, content={"message": str(exc.detail)})


@app.exception_handler(Exception)
async def unhandled_exception_handler(request: Request, exc: Exception):
    # Safety net: guarantees JSON always comes back (every frontend caller
    # does res.json() on error paths) WITHOUT echoing exception text, which
    # can carry file paths, SQL, provider URLs or key fragments. The detail
    # goes to the server log only.
    log.exception("Unhandled error on %s", request.url.path)
    security.audit("unhandled_error", actor=_client_id(request), outcome="http_500",
                   resource=request.url.path, details={"type": type(exc).__name__})
    return JSONResponse(status_code=500, content={"message": "Unexpected server error."})


def _ai_unavailable(exc: Exception, what: str) -> JSONResponse:
    """503 without leaking provider endpoints / internal messages to the caller."""
    log.warning("%s failed: %s", what, security.redact(exc))
    security.audit("ai_unavailable", outcome="http_503", resource=what, details={"error": security.redact(exc)})
    return JSONResponse(
        status_code=503,
        content={"message": "The AI service is temporarily unavailable. Please try again shortly."},
    )


def _label_ai(payload: dict) -> dict:
    """Transparency + human-oversight markers on every AI-produced response."""
    if isinstance(payload, dict):
        payload["ai_generated"] = True
        payload["ai_disclosure"] = AI_DISCLOSURE
        payload["human_review_required"] = True
    return payload


