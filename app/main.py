    try:
        plan_result = run_agent5_from_score(payload.score, blueprint, max_steps=payload.max_steps)
        return _label_ai(build_dev_dashboard(
            plan_result,
            evidence_report=payload.evidence,
            mcq_score_pct=payload.score.get("overall_score_pct"),
        ))
    except (RuntimeError, ValueError) as exc:
        return _ai_unavailable(exc, "devplan")


